/**
 * Helper to get localized Surah Name and Meaning
 */
export const getLocalizedSurah = (surahNumber: number, lang: AppLanguage, fallbackEnglish: string, fallbackArabic: string, fallbackTranslation: string): { name: string; translation: string } => {
  const surahData = SURAH_LOCALE_NAMES[surahNumber];
  if (surahData && surahData[lang]) {
    return surahData[lang];
  }
  if (surahData && surahData.en) {
    return surahData.en;
  }
  return { name: fallbackEnglish, translation: fallbackTranslation };
};
